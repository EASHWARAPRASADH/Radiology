"""FHIR R4B DiagnosticReport (+ contained Observations) for the AI draft.

* status = "preliminary" until a radiologist approves -> "final" (or "amended" after an amendment).
* AI origin is tagged in ``meta.tag`` with a local code system. HL7's own AI-provenance codes should
  replace it once verified (see docs/blueprint/10-system-architecture.md).
* Observations carry valueCodeableConcept present/absent/indeterminate; not-assessed concepts are
  emitted with dataAbsentReason="not-performed", never as negatives.
"""

from __future__ import annotations

from fhir.resources.R4B.diagnosticreport import DiagnosticReport

from radio.ontology.cxr import PRIVATE_CODING_SCHEME
from radio.schema.findings import AnalysisResult, FindingStatus, ReviewStatus

LOCAL_SYSTEM = "urn:radio:codesystem"
_SCT = "http://snomed.info/sct"
_VALUE = {
    FindingStatus.present: (_SCT, "52101004", "Present"),
    FindingStatus.absent: (_SCT, "272519000", "Absent"),
    FindingStatus.uncertain: (_SCT, "82334004", "Indeterminate"),
}
_STATUS = {ReviewStatus.approved: "final", ReviewStatus.amended: "amended", ReviewStatus.rejected: "cancelled"}


def build_diagnostic_report(result: AnalysisResult) -> DiagnosticReport:
    observations = []
    for f in result.findings:
        obs = {
            "resourceType": "Observation",
            "id": f"f-{f.id[:12]}",
            "status": "preliminary" if result.review_status == ReviewStatus.draft else "final",
            "code": {"coding": [{"system": f"{LOCAL_SYSTEM}:{PRIVATE_CODING_SCHEME}", "code": f.code,
                                 "display": f.display}]},
        }
        if f.status == FindingStatus.not_assessed:
            obs["dataAbsentReason"] = {"coding": [{
                "system": "http://terminology.hl7.org/CodeSystem/data-absent-reason", "code": "not-performed"}]}
        else:
            system, code, display = _VALUE[f.status]
            obs["valueCodeableConcept"] = {"coding": [{"system": system, "code": code, "display": display}]}
            if f.evidence is not None:
                obs["note"] = [{"text": f"AI calibrated probability {f.evidence.calibrated_probability:.3f} "
                                        f"({f.evidence.model_version})"}]
        observations.append(obs)

    text = result.report.to_text() if result.report else "AI abstained; no draft report."
    authored = result.radiologist_text()
    if authored:
        text = authored[1]
    dr = {
        "resourceType": "DiagnosticReport",
        "id": result.result_id,
        "meta": {"tag": [{"system": LOCAL_SYSTEM, "code": "ai-generated-draft",
                          "display": "Generated by AI; requires radiologist review"}]},
        "status": _STATUS.get(result.review_status, "preliminary"),
        "category": [{"coding": [{"system": "http://terminology.hl7.org/CodeSystem/v2-0074", "code": "RAD",
                                  "display": "Radiology"}]}],
        "code": {"coding": [{"system": LOCAL_SYSTEM, "code": "cxr-ai-report", "display": "Chest radiograph report"}],
                 "text": "Chest radiograph report"},
        "contained": observations,
        "result": [{"reference": f"#{o['id']}"} for o in observations],
        "conclusion": " ".join(result.impression) or None,
        "presentedForm": [{"contentType": "text/plain", "title": "Report", "data": _b64(text)}],
    }
    if result.study.study_instance_uid:
        dr["identifier"] = [{"system": "urn:dicom:uid", "value": f"urn:oid:{result.study.study_instance_uid}"}]
    return DiagnosticReport.model_validate({k: v for k, v in dr.items() if v is not None})


def _b64(s: str) -> str:
    import base64

    return base64.b64encode(s.encode()).decode()
